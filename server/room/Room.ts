import type { Connection, WSMessage } from "partyserver";
import { Server } from "partyserver";

import { CLOSE_REPLACED } from "@/online/closeCodes";
import { parseClientMessage } from "@/online/parseClientMessage";

import type { Player } from "@/types/HexTile";
import type { PlayerInfo } from "@/types/Online";

import type { ConnectionState } from "@server/connection";
import { isReady, send, tokenOf } from "@server/connection";
import {
  CLAIM_PATH,
  CREATED_KEY,
  EMPTY_ROOM_SECONDS,
  GAME_KEY,
  MAX_PLAYERS,
  SIDES_KEY,
  TOKENS_KEY,
  TURN_MS,
} from "@server/constants";
import { getDictionary } from "@server/dictionary";
import type { Sides } from "./lobby";
import { canBeReady, everyoneReady } from "./lobby";
import type { StoredGame } from "./turn";
import {
  expireTurn,
  isRunning,
  isTurnOf,
  msUntilTurnEnds,
  playMove,
  selectableKeys,
  startGame,
} from "./turn";

export type Env = { Main: DurableObjectNamespace<Room> };

/**
 * One online game room.
 *
 * Each room code is a separate `Room`.
 *
 * A player is identified by a token, which is generated by the room when they first joins and is kept in its storage.
 *
 * The token lets a player reconnects on a new connection and still be the same player.
 */
export class Room extends Server<Env> {
  /** Lets the room sleep while nobody sends anything. */
  static options = { hibernate: true };

  /**
   * Handles plain requests to the room.
   *
   * @param request - The request.
   * @returns `409` if the room was already created, so the caller picks another code.
   */
  async onRequest(request: Request): Promise<Response> {
    const { pathname } = new URL(request.url);
    if (request.method !== "POST" || pathname !== CLAIM_PATH)
      return new Response("Not Found", { status: 404 });

    if (await this.isCreated())
      return new Response("Room already exists", { status: 409 });

    await this.ctx.storage.put(CREATED_KEY, true);
    await this.scheduleCleanup();
    return new Response("Created");
  }

  /** Reads a message from a player and handles it. */
  async onMessage(connection: Connection, message: WSMessage) {
    const parsed =
      typeof message === "string" ? parseClientMessage(message) : null;
    if (!parsed) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    switch (parsed.type) {
      case "join":
        await this.join(connection, parsed.token);
        return;
      case "choose-side":
        await this.chooseSide(connection, parsed.side);
        return;
      case "set-ready":
        await this.setReady(connection, parsed.ready);
        return;
      case "leave":
        await this.leave(connection);
        return;
      case "submit":
        await this.submit(connection, parsed.keys);
        return;
      case "select":
        await this.select(connection, parsed.keys);
        return;
    }
  }

  /** Tells the other player that someone left, and starts the cleanup timer if the room is now empty. */
  async onClose(connection: Connection) {
    await this.broadcastRoom(connection);

    const othersOpen = Array.from(this.getConnections()).some(
      (other) => other.id !== connection.id,
    );
    if (!othersOpen && (await this.isCreated())) await this.scheduleCleanup();
  }

  /**
   * Runs when the room's alarm goes off, checking:
   * - If nobody is connected, then we starts an empty-room timer. Once it runs out, the room's storage is deleted.
   * - If someone is connected, the turn timer ended, so the turn of the player who ran out of time is passed.
   */
  async onAlarm() {
    if (Array.from(this.getConnections()).length === 0) {
      await this.ctx.storage.deleteAll();
      return;
    }

    const game = await this.getGame();
    if (game === null) return;

    const next = expireTurn(game, getDictionary(), Date.now());
    if (next === game) {
      await this.armTurnTimer(game);
      return;
    }

    await this.putGame(next);
    await this.broadcastGame();
  }

  /**
   * Lets a connection join the room as a player, then tells the room which player it is.
   *
   * If `token` is known then the player is brought back as themselves. A new player gets a new token if there is space.
   *
   * If the same player is already connected else, the older connection is closed.
   *
   * If a game is being played, the player is sent to that game.
   *
   * @param connection - The connection that sent `join`.
   * @param token - The token from an earlier `welcome`, or `null` for a new player.  
   */
  private async join(connection: Connection, token: string | null) {
    if (tokenOf(connection) !== null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    if (!(await this.isCreated())) {
      send(connection, { type: "error", reason: "room-not-found" });
      return;
    }

    const tokens = await this.getTokens();
    let own = token !== null && tokens.includes(token) ? token : null;

    if (own === null) {
      if (tokens.length >= MAX_PLAYERS) {
        send(connection, { type: "error", reason: "room-full" });
        return;
      }
      own = crypto.randomUUID();
      tokens.push(own);
      await this.ctx.storage.put(TOKENS_KEY, tokens);
    }

    const roomWasEmpty = !Array.from(this.getConnections()).some(
      (other) => other.id !== connection.id && tokenOf(other) !== null,
    );

    for (const other of this.getConnections()) {
      if (other.id !== connection.id && tokenOf(other) === own) {
        other.setState({ token: own, ready: false } satisfies ConnectionState);
        other.close(CLOSE_REPLACED, "replaced");
      }
    }

    await this.ctx.storage.deleteAlarm();

    connection.setState({ token: own, ready: false } satisfies ConnectionState);
    send(connection, { type: "welcome", token: own });
    await this.broadcastRoom();

    const game = await this.getGame();
    if (game === null) return;

    const current =
      roomWasEmpty && isRunning(game)
        ? { ...game, turnEndsAt: Date.now() + TURN_MS }
        : game;
    if (current !== game) await this.putGame(current);
    else await this.armTurnTimer(current);

    this.sendGame(connection, current, own, await this.getSides());
  }

  /**
   * Lets a player selects, or unselects a side.
   *
   * Both players can select the same side but they will be refused if they set `ready` with the same side selected.
   *
   * The sides are locked once a game has started.
   *
   * @param connection - The connection that sent `choose-side`.
   * @param side - The side to select, or `null` to unselect.
   */
  private async chooseSide(connection: Connection, side: Player | null) {
    const own = tokenOf(connection);
    if (own === null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    if (!isReady(connection) && (await this.getGame()) === null) {
      const sides = await this.getSides();
      if (side === null) delete sides[own];
      else sides[own] = side;
      await this.ctx.storage.put(SIDES_KEY, sides);
    }

    await this.broadcastRoom();
  }

  /**
   * Sets whether a player is ready to start.
   *
   * Becoming ready is refused if the player has not selected a side, or if the other player is already ready on the same side.
   *
   * @param connection - The connection that sent `set-ready`.
   * @param ready - `true` to become ready, `false` to stop being ready.
   */
  private async setReady(connection: Connection, ready: boolean) {
    const own = tokenOf(connection);
    if (own === null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    const game = await this.getGame();
    let started = false;

    if (!isRunning(game)) {
      const sides = await this.getSides();
      if (!ready || canBeReady(own, sides, this.readyTokens()))
        connection.setState({ token: own, ready } satisfies ConnectionState);

      started = await this.startGameIfReady(game);
    }

    await this.broadcastRoom();
    if (started) await this.broadcastGame();
  }

  /**
   * Starts a game if both players are in the room and ready.
   *
   * Starting a game makes both players not ready, so they must press ready again to play again.
   *
   * @param previous - The game that has finished in this room, `null` if there is none.
   * @returns `true` if a game started.
   */
  private async startGameIfReady(
    previous: StoredGame | null,
  ): Promise<boolean> {
    if (!everyoneReady(await this.getTokens(), this.readyTokens()))
      return false;

    for (const connection of this.getConnections()) {
      const token = tokenOf(connection);
      if (token !== null)
        connection.setState({ token, ready: false } satisfies ConnectionState);
    }

    await this.putGame(startGame(previous, getDictionary(), Date.now()));
    return true;
  }

  /**
   * Plays a word for a player, if it is their turn and the word is valid.
   *
   * @param connection - The connection that sent `submit`.
   * @param keys - The keys of the selected tiles, in word order.
   */
  private async submit(connection: Connection, keys: string[]) {
    const own = tokenOf(connection);
    if (own === null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    const stored = await this.getGame();
    if (stored === null) {
      await this.broadcastRoom();
      return;
    }

    const dictionary = getDictionary();
    const sides = await this.getSides();

    const game = expireTurn(stored, dictionary, Date.now());
    const next = isTurnOf(game, sides, own)
      ? playMove(game, { type: "submit", keys }, dictionary, Date.now())
      : null;

    const changed = next ?? game;
    if (changed !== stored) {
      await this.putGame(changed);
      await this.broadcastGame();
    } else {
      this.sendGame(connection, game, own, sides);
    }
  }

  private async select(connection: Connection, keys: string[]) {
    const own = tokenOf(connection);
    if (own === null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    const game = await this.getGame();
    if (game === null || !isTurnOf(game, await this.getSides(), own)) return;

    const selection = selectableKeys(game, keys);
    for (const other of this.getConnections()) {
      const token = tokenOf(other);
      if (token !== null && token !== own)
        send(other, { type: "selection", keys: selection });
    }
  }

  /**
   * Removes a player from the room for good, sets their seat, side and token available.
   *
   * This also ends a running game.
   *
   * @param connection - The connection that sent `leave`.
   */
  private async leave(connection: Connection) {
    const own = tokenOf(connection);
    if (own === null) {
      send(connection, { type: "error", reason: "invalid-message" });
      return;
    }

    const tokens = (await this.getTokens()).filter((token) => token !== own);
    await this.ctx.storage.put(TOKENS_KEY, tokens);

    const sides = await this.getSides();
    delete sides[own];
    await this.ctx.storage.put(SIDES_KEY, sides);
    await this.ctx.storage.delete(GAME_KEY);

    connection.setState(null);
    await this.broadcastRoom();
  }

  /**
   * Sends all joined player the current state of the room.
   *
   * @param closing - A connection that is closing. It is not counted as connected and doesn't get notified of the room state.
   */
  private async broadcastRoom(closing?: Connection) {
    const tokens = await this.getTokens();
    const sides = await this.getSides();
    const inGame = (await this.getGame()) !== null;
    const connected = new Set<string>();
    const ready = new Set<string>();

    for (const connection of this.getConnections()) {
      if (connection.id === closing?.id) continue;
      const token = tokenOf(connection);
      if (token === null) continue;
      connected.add(token);
      if (isReady(connection)) ready.add(token);
    }

    const infoOf = (token: string): PlayerInfo => ({
      connected: connected.has(token),
      side: sides[token] ?? null,
      ready: ready.has(token),
    });

    for (const connection of this.getConnections()) {
      if (connection.id === closing?.id) continue;
      const own = tokenOf(connection);
      if (own === null) continue;

      const otherToken = tokens.find((token) => token !== own);
      const opponent = otherToken === undefined ? null : infoOf(otherToken);

      send(connection, {
        type: "room",
        self: infoOf(own),
        opponent,
        inGame,
      });
    }
  }

  /** Sends every joined player the current game. */
  private async broadcastGame() {
    const game = await this.getGame();
    if (game === null) return;

    const sides = await this.getSides();
    for (const connection of this.getConnections()) {
      const token = tokenOf(connection);
      if (token !== null) this.sendGame(connection, game, token, sides);
    }
  }

  /**
   * Sends a player their side of the game.
   *
   * @param connection - The player's connection.
   * @param game - The game.
   * @param token - The player's token.
   * @param sides - The side each player has taken, by token.
   */
  private sendGame(
    connection: Connection,
    game: StoredGame,
    token: string,
    sides: Sides,
  ) {
    const you = sides[token];
    if (you === undefined) return;

    send(connection, {
      type: "game",
      state: game.state,
      you,
      turnEndsInMs: msUntilTurnEnds(game, Date.now()),
    });
  }

  /** Starts the timer that deletes the room if the room is empty. */
  private async scheduleCleanup() {
    await this.ctx.storage.setAlarm(Date.now() + EMPTY_ROOM_SECONDS * 1000);
  }

  /** Sets the alarm to go off when the turn runs out, or removes it if the game is over. */
  private async armTurnTimer(game: StoredGame) {
    if (game.turnEndsAt === null) await this.ctx.storage.deleteAlarm();
    else await this.ctx.storage.setAlarm(game.turnEndsAt);
  }

  /** The players who are ready, by token. */
  private readyTokens(): Set<string> {
    const ready = new Set<string>();
    for (const connection of this.getConnections()) {
      const token = tokenOf(connection);
      if (token !== null && isReady(connection)) ready.add(token);
    }
    return ready;
  }

  /** If the room was made by `POST /rooms`. */
  private async isCreated(): Promise<boolean> {
    return (await this.ctx.storage.get<boolean>(CREATED_KEY)) === true;
  }

  /** The tokens of the players in the room, in the order they joined. */
  private async getTokens(): Promise<string[]> {
    return (await this.ctx.storage.get<string[]>(TOKENS_KEY)) ?? [];
  }

  /** The side each player has taken, by token. */
  private async getSides(): Promise<Sides> {
    return (await this.ctx.storage.get<Sides>(SIDES_KEY)) ?? {};
  }

  /** The game being played in the room, or `null` if there is none. */
  private async getGame(): Promise<StoredGame | null> {
    return (await this.ctx.storage.get<StoredGame>(GAME_KEY)) ?? null;
  }

  /** Keeps the game, and sets the alarm for its turn timer. */
  private async putGame(game: StoredGame) {
    await this.ctx.storage.put(GAME_KEY, game);
    await this.armTurnTimer(game);
  }
}
